# --- tiny YAML writer (no dependency; values here are scalars, lists and dicts) -------

def _fmt(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    if isinstance(v, (float, np.floating)):
        f = float(v)
        return repr(int(f)) if f.is_integer() and abs(f) < 1e15 else repr(f)
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_fmt(x) for x in v) + "]"
    s = str(v)
    if s == "" or any(c in s for c in ":#{}[]&*!|>%@`\"'") or s.strip() != s:
        return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
    return s


def yaml_dump(d, indent=0, lines=None):
    lines = [] if lines is None else lines
    pad = "  " * indent
    for k, v in d.items():
        if isinstance(v, dict):
            if not v:
                lines.append(f"{pad}{k}: {{}}")
            else:
                lines.append(f"{pad}{k}:")
                yaml_dump(v, indent + 1, lines)
        elif isinstance(v, list) and v and isinstance(v[0], dict):
            lines.append(f"{pad}{k}:")
            for item in v:
                sub = yaml_dump(item, indent + 2).splitlines()
                lines.append(f"{pad}  - {sub[0].strip()}")
                lines.extend(sub[1:])
        else:
            lines.append(f"{pad}{k}: {_fmt(v)}")
    return "\n".join(lines) + ("\n" if indent == 0 else "")


def write(path: Path, text: str, check: bool, stale: list):
    path.parent.mkdir(parents=True, exist_ok=True)
    if check:
        if not path.exists() or path.read_text() != text:
            stale.append(str(path.relative_to(OUT.parent)))
        return
    path.write_text(text)


def header(title: str, note: str) -> str:
    return (f"# {title}\n"
            f"# {note}\n"
            f"# GENERATED by experiments/benchmark/generate_configs.py -- do not edit by\n"
            f"# hand; edit the registry or train.py and regenerate.\n\n")


