"""Emit one config file per trainable configuration, read from the live registry.

These files exist to be reviewed and diffed by a human -- in a merge discussion, in a
paper appendix -- so they are GENERATED rather than hand-written. Every number here is
read from the code that will actually run: the `EnvSpec`, the `MethodSpec`, the argparse
defaults in ``train.py``, the pretraining recipes in ``pretrain/3_pretrain_encoder.py``,
and the parameter counts of the instantiated modules. Hand-maintained copies of this
information drift silently; a regenerated file that differs from the committed one is a
visible diff.

    python experiments/benchmark/generate_configs.py            # writes configs/
    python experiments/benchmark/generate_configs.py --check    # non-zero if stale

Layout:
    configs/_shared.yaml          protocol every run obeys (head, seeds, eval, fairness)
    configs/algorithms/*.yaml     PPO / SAC hyperparameters
    configs/envs/*.yaml           one per registered environment
    configs/methods/*.yaml        one per registered method (the encoder configuration)
    configs/pretraining/*.yaml    one per encoder family that can be pretrained
    configs/README.md             index + how to read them
"""

from __future__ import annotations

import argparse
import inspect
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
sys.path.insert(0, str(Path(__file__).resolve().parent))

