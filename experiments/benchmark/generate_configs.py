def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit non-zero if any file is missing or stale")
    args = ap.parse_args()

    defaults = cli_defaults()
    stale: list[str] = []
    emit_shared(defaults, args.check, stale)
    emit_algorithms(defaults, args.check, stale)
    emit_envs(args.check, stale)
    emit_methods(defaults, args.check, stale)
    emit_pretraining(args.check, stale)
    emit_readme(defaults, args.check, stale)

    if args.check:
        if stale:
            print("STALE (regenerate):")
            for s in stale:
                print("  " + s)
            raise SystemExit(1)
        print("configs are up to date")
    else:
        n = sum(1 for _ in OUT.rglob("*") if _.is_file())
        print(f"wrote {n} files under {OUT.relative_to(Path.cwd()) if OUT.is_relative_to(Path.cwd()) else OUT}")


if __name__ == "__main__":
    main()
