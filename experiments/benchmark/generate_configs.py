def cli_defaults() -> dict:
    """argparse defaults from train.py, so the files cannot disagree with the trainer."""
    parser = argparse.ArgumentParser()
    src = inspect.getsource(train_mod.main)
    ns = {"argparse": argparse, "ALGOS": train_mod.ALGOS, "p": parser}
    for line in src.splitlines():
        line = line.strip()
        if line.startswith("p.add_argument("):
            try:
                eval(line, ns)          # noqa: S307 - our own source, fixed shape
            except Exception:
                pass
    return {a.dest: a.default for a in parser._actions if a.dest != "help"}


def env_spaces(env_name: str):
    """Observation shapes as the policy sees them, from the real wrapper stack."""
    spec = ENV_REGISTRY[env_name]
    env = train_mod.make_env_thunk(spec, 0, for_eval=True)()
    obs, _ = env.reset(seed=0)
    inner = env
    while inner is not None and not hasattr(inner, "particle_filter"):
        inner = getattr(inner, "env", None)
    out = {
        "obs_dim": int(np.asarray(obs["obs"]).shape[0]),
        "num_particles": int(np.asarray(obs["particles"]).shape[0]),
        "particle_dim": int(np.asarray(obs["particles"]).shape[1]),
        "action_space": str(env.action_space),
    }
    env.close()
    return out


def extractor_facts(method: str, env_name: str, spaces_info: dict, defaults: dict):
    """Resolved kwargs + parameter counts for one (method, env) pair."""
    import gymnasium as gym

    spec = METHOD_REGISTRY[method]
    space = gym.spaces.Dict({
        "obs": gym.spaces.Box(-np.inf, np.inf, (spaces_info["obs_dim"],)),
        "particles": gym.spaces.Box(-np.inf, np.inf,
                                    (spaces_info["num_particles"], spaces_info["particle_dim"])),
    })
    arch = dict(num_encodings=defaults["num_encodings"], dim_encoder=defaults["dim_encoder"],
                num_inds=defaults["num_inds"], dim_hidden=defaults["dim_hidden"],
                num_heads=defaults["num_heads"], ln=not defaults["no_ln"])
    kwargs = dict(build_extractor_kwargs(
        spec, defaults["features_dim"], defaults["obs_mlp_hidden_dims"],
        pretrained_model_path="<checkpoint>" if spec.extractor_kwargs.get("freeze") else None,
        encoder_arch=arch, particle_scale=ENV_REGISTRY[env_name].particle_scale,
    ))
    built = {k: v for k, v in kwargs.items() if k != "pretrained_model_path"}
    built.pop("freeze", None)
    ext = spec.extractor_class(space, **built)
    total = sum(p.numel() for p in ext.parameters())
    head = (sum(p.numel() for p in ext.obs_net.parameters())
            + sum(p.numel() for p in ext.combined_net.parameters()))
    frozen = bool(spec.extractor_kwargs.get("freeze"))
    return {
        "extractor_class": spec.extractor_class.__name__,
        "resolved_kwargs": {k: (list(v) if isinstance(v, (list, tuple)) else v)
                            for k, v in sorted(kwargs.items())},
        "particle_stat_dim": int(ext._particle_stat_dim()),
        "params": {
            "encoder_only": int(ext.particle_encoder_parameters()),
            "shared_head": int(head),
            "extractor_total": int(total),
            "trainable_in_rl": int(head if frozen else total),
        },
    }


