def emit_algorithms(defaults, check, stale):
    ppo, sac = _ppo_doc(defaults), _sac_doc(defaults)
    ppo_head = ppo["architecture"]["heads"]["continuous"]["params"]["policy_mlp"]
    sac_head = sac["architecture"]["actor"]["params"]["latent_pi"]
    comparability = {
        "comparability_with_other_algorithm": {
            "head_widths_differ": (f"PPO uses {ppo['architecture']['net_arch']['pi']} "
                                   f"{ppo['architecture']['activation_fn']}; SAC uses "
                                   f"{sac['architecture']['net_arch']} "
                                   f"{sac['architecture']['activation_fn']}"),
            "actor_hidden_params": {"ppo": ppo_head, "sac": sac_head,
                                    "ratio": round(sac_head / ppo_head, 1)},
            "trainable_extractor_copies": {"ppo": 1, "sac": 2},
            "implication": ("a SAC-vs-PPO difference is also a head-capacity and "
                            "encoder-copy difference; it is not a pure algorithm effect "
                            "unless net_arch is pinned to match"),
        }
    }
    ppo.update(comparability)
    sac.update(comparability)
    write(OUT / "algorithms" / "ppo.yaml",
          header("PPO", "Read from a live model built by train.py::build_model.")
          + yaml_dump(ppo), check, stale)
    write(OUT / "algorithms" / "sac.yaml",
          header("SAC", "Read from a live model built by train.py::build_model.")
          + yaml_dump(sac), check, stale)


def _potential_name(fn):
    """Readable name for a potential, including closures built by a factory.

    ``pf_belief_information_potential(scale=...)`` returns an inner function called
    ``_potential``; reporting that would tell a reader nothing, so recover the factory
    name and the captured arguments from the closure.
    """
    if fn is None:
        return None
    name = getattr(fn, "__qualname__", getattr(fn, "__name__", "<closure>"))
    if "." in name:                      # e.g. "pf_belief_information_potential.<locals>._potential"
        factory = name.split(".")[0]
        captured = {}
        if fn.__closure__:
            for var, cell in zip(fn.__code__.co_freevars, fn.__closure__):
                try:
                    val = cell.cell_contents
                except ValueError:
                    continue
                if isinstance(val, (int, float, str, bool)):
                    captured[var] = val
        return f"{factory}({', '.join(f'{k}={v}' for k, v in sorted(captured.items()))})"
    return name


def emit_envs(check, stale):
    for name, spec in ENV_REGISTRY.items():
        try:
            spaces_info = env_spaces(name)
        except Exception as exc:                     # MuJoCo envs may be unavailable
            spaces_info = {"error": f"could not build env: {type(exc).__name__}: {exc}"}
        doc = {
            "env": name,
            "builder": f"{spec.make_base_env.__module__}.{spec.make_base_env.__name__}",
            "base_env_kwargs": dict(spec.base_env_kwargs),
            "spaces": spaces_info,
            "belief": {
                "particle_filter": spec.particle_filter_class.__name__,
                "num_particles": spec.num_particles,
                "particle_filter_kwargs": dict(spec.particle_filter_kwargs),
                "pf_kwargs_from_env": bool(spec.pf_kwargs_from_env),
                "pf_mapper": spec.pf_mapper.__name__ if spec.pf_mapper else None,
                "obs_mask_indices": (f"{spec.obs_mask_indices[0]}..{spec.obs_mask_indices[-1]}"
                                     if spec.obs_mask_indices else None),
                "particles_relative_to_agent": bool(spec.particle_origin_fn),
            },
            "reward": {
                "shaping_potential": _potential_name(spec.potential_fn),
                "shaping_gamma": spec.shaping_gamma,
                "shaping_zero_at_termination": spec.shaping_zero_at_termination,
                "success_criterion": spec.success_criterion,
            },
            "training": {
                "default_algo": spec.default_algo,
                "default_timesteps": spec.default_timesteps,
                "gamma": spec.gamma,
                "max_ep_steps": spec.max_ep_steps,
                "particle_scale": spec.particle_scale,
            },
        }
        write(OUT / "envs" / f"{name}.yaml",
              header(f"Environment: {name}", "EnvSpec as registered.") + yaml_dump(doc),
              check, stale)


def emit_methods(defaults, check, stale):
    ref_env = "msearch" if "msearch" in ENV_REGISTRY else next(iter(ENV_REGISTRY))
    spaces_info = env_spaces(ref_env)
    for method in METHOD_ORDER:
        spec = METHOD_REGISTRY[method]
        facts = extractor_facts(method, ref_env, spaces_info, defaults)
        arm = ("aligned" if spec.aligned else
               ("unaligned" if spec.encoder_kind and
                (method.endswith("_frozen") or method.endswith("_finetune")) else None))
        doc = {
            "method": method,
            "family": spec.encoder_kind or "analytic",
            "pretrained": bool(spec.extractor_kwargs.get("freeze") is not None
                               and (method.endswith("_frozen") or method.endswith("_finetune"))),
            "encoder_weights": ("frozen" if spec.extractor_kwargs.get("freeze")
                                else ("fine-tuned" if method.endswith("_finetune")
                                      else "trained from scratch with the policy")),
            "pretraining_arm": arm,
            "checkpoint": (f"pretrained/<env>/{spec.encoder_kind}_"
                           f"{'align' if spec.aligned else 'plain'}/checkpoint_best.pt"
                           if arm else None),
            "reference_env": ref_env,
            **facts,
        }
        write(OUT / "methods" / f"{method}.yaml",
              header(f"Method: {method}",
                     f"Parameter counts measured at {ref_env} "
                     f"(d={spaces_info['particle_dim']}, obs={spaces_info['obs_dim']}).")
              + yaml_dump(doc),
              check, stale)


def emit_pretraining(check, stale):
    import importlib.util
    path = Path(__file__).resolve().parent / "pretrain" / "3_pretrain_encoder.py"
    spec_ = importlib.util.spec_from_file_location("_pre", path)
    pre = importlib.util.module_from_spec(spec_)
    spec_.loader.exec_module(pre)

    ap_defaults = {}
    parser = argparse.ArgumentParser()
    src = inspect.getsource(pre.main)
    ns = {"argparse": argparse, "Path": Path, "ap": parser, "ENCODERS": pre.ENCODERS,
          "DEFAULT_DATA": pre.DEFAULT_DATA, "DEFAULT_OUT": pre.DEFAULT_OUT,
          "DEFAULT_BLUR": pre.DEFAULT_BLUR, "torch": __import__("torch")}
    for line in src.splitlines():
        line = line.strip()
        if line.startswith("ap.add_argument("):
            try:
                eval(line, ns)      # noqa: S307
            except Exception:
                pass
    ap_defaults = {a.dest: a.default for a in parser._actions if a.dest != "help"}

    for kind, (cls, arch) in pre.ENCODERS.items():
        doc = {
            "encoder_family": kind,
            "autoencoder_class": cls.__name__,
            "architecture": {k: (str(v) if isinstance(v, Path) else v)
                             for k, v in arch.items()},
            "bottleneck": {
                "num_encodings": ap_defaults.get("num_encodings"),
                "dim_encoder": ap_defaults.get("dim_encoder"),
                "stat_dim": (ap_defaults.get("num_encodings", 0)
                             * ap_defaults.get("dim_encoder", 0)),
            },
            "optimization": {
                "num_epochs": ap_defaults.get("num_epochs"),
                "batch_size": ap_defaults.get("batch_size"),
                "learning_rate": ap_defaults.get("lr"),
                "reconstruction_loss": ap_defaults.get("loss"),
                "sinkhorn_blur": ap_defaults.get("blur"),
                "model_selection": "best exact val EMD (independent of the training loss)",
            },
            "alignment_arm": {
                "enabled_by": "--align",
                "objective": "reconstruction + lambda * (1 - Pearson(latent dists, EMD dists))",
                "lambda": ap_defaults.get("align_lambda"),
                "metric": ap_defaults.get("align_metric"),
                "warmup_epochs": ap_defaults.get("align_warmup"),
                "ramp_epochs": ap_defaults.get("align_ramp"),
                "requires": "pairwise EMD matrix from pretrain/2_precompute_emd.py",
                "hazard": ("model selection is by val EMD and blind to alignment; if the "
                           "best epoch precedes the end of the lambda ramp the checkpoint "
                           "is not actually aligned. The trainer warns and records "
                           "best_epoch / selected_val_r"),
            },
            "produces": f"pretrained/<env>/{kind}_{{plain,align}}/checkpoint_best.pt",
        }
        write(OUT / "pretraining" / f"{kind}.yaml",
              header(f"Pretraining: {kind}",
                     "Autoencoder recipe; arch must match what the RL extractor builds.")
              + yaml_dump(doc),
              check, stale)


